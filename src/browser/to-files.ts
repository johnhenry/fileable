/**
 * `toFiles()` (browser-safe): Build -> Resolve -> Layout, then collect the
 * final loose file contents into a plain `{ relativePosixPath: content }`
 * object instead of writing them anywhere. Hash (Stage 4) is skipped, it
 * only feeds the incremental-build cache, which has no meaning here.
 *
 * Decisions (documented in README "Browser usage"):
 *  - Only files appear in the result; directories are implied by paths, so
 *    an empty `<Dir>` produces no entry.
 *  - `encode="zip"` / `encode="wbn"` anywhere in the tree throw a clear
 *    "not supported in the browser" error. Producing archive bytes is a
 *    Node Write-stage concern (`render()`); the browser entry stays small.
 *  - `onConflict` and `<Rm>` act on an in-memory stand-in for "what is
 *    already there": `options.existing` (a `Files` object, never mutated).
 *    Without `existing` nothing pre-exists, so every `onConflict` mode
 *    behaves like "replace" and `<Rm>` removes nothing (`onMissing`
 *    "warn"/"error" still apply to it). Files generated by this tree are
 *    never removed by its own `<Rm>` (matches `render()`: removals run
 *    before writes).
 *  - Symlinks are materialized as copies (there is no filesystem).
 *  - Every output path is validated: relative POSIX only, no `..`, no
 *    absolute path / drive letter, no backslash, no NUL.
 */
import { minimatch } from "minimatch";
import { build } from "../build.js";
import { layout } from "../layout.js";
import { cloneDescriptorTree, FileableError } from "../types.js";
import type { RemovalSpec, RenderOptions } from "../types.js";
import { resolve } from "./resolve.js";
import { bufferToContent } from "./content-util.js";
import { drainBuildContext } from "../context.js";

/** Final path (relative, POSIX) -> content: `string` for text, `Uint8Array` for binary. */
export interface Files {
  [relativePosixPath: string]: string | Uint8Array;
}

export interface ToFilesOptions extends RenderOptions {
  /**
   * In-memory stand-in for files that "already exist": the target of
   * `onConflict` and `<Rm>`. Returned `Files` = `existing` (minus removals)
   * overlaid with the generated files. Not mutated.
   */
  existing?: Files;
}

const ON_CONFLICT_VALUES = new Set(["replace", "append", "prepend", "skip", "error"]);

function setFile(files: Files, path: string, content: string | Uint8Array): void {
  // defineProperty so a path literally named "__proto__" is an own key, not a prototype write.
  Object.defineProperty(files, path, { value: content, enumerable: true, writable: true, configurable: true });
}

function has(files: Files, path: string): boolean {
  return Object.prototype.hasOwnProperty.call(files, path);
}

function assertSafePath(path: string): void {
  const reason =
    path === "" || path === "."
      ? "empty path"
      : path.includes("\0")
        ? "contains NUL"
        : path.includes("\\")
          ? "contains a backslash"
          : path.startsWith("/") || /^[A-Za-z]:/.test(path)
            ? "absolute path"
            : path.split("/").includes("..")
              ? 'contains a ".." segment'
              : path.split("/").includes("")
                ? "contains an empty segment"
                : undefined;
  if (reason) {
    throw new FileableError(
      `unsafe output path ${JSON.stringify(path)} (${reason}) -- toFiles() only produces relative POSIX paths inside the tree`,
      path,
    );
  }
}

function toBytes(content: string | Uint8Array): Uint8Array {
  return typeof content === "string" ? new TextEncoder().encode(content) : content;
}

function combine(a: string | Uint8Array, b: string | Uint8Array): string | Uint8Array {
  if (typeof a === "string" && typeof b === "string") return a + b;
  const x = toBytes(a);
  const y = toBytes(b);
  const out = new Uint8Array(x.length + y.length);
  out.set(x, 0);
  out.set(y, x.length);
  return bufferToContent(out);
}

function parseOnConflict(props: Record<string, unknown>, path: string): "replace" | "append" | "prepend" | "skip" | "error" {
  const value = props.onConflict;
  if (value === undefined) return "replace";
  if (typeof value === "string" && ON_CONFLICT_VALUES.has(value)) return value as "replace";
  throw new FileableError(
    `invalid onConflict="${String(value)}" -- expected "replace", "append", "prepend", "skip", or "error"`,
    path,
  );
}

async function applyRemovals(removals: RemovalSpec[], files: Files, warnings: string[]): Promise<void> {
  for (const spec of removals) {
    const negated = spec.pattern.startsWith("!");
    const pattern = (negated ? spec.pattern.slice(1) : spec.pattern).replace(/\\/g, "/");
    const matches = (path: string): boolean => {
      const hit = minimatch(path, pattern, { dot: true });
      return negated ? !hit : hit;
    };
    const filePaths = Object.keys(files);
    const dirPaths = new Set<string>();
    for (const p of filePaths) {
      const parts = p.split("/");
      for (let i = 1; i < parts.length; i++) dirPaths.add(parts.slice(0, i).join("/"));
    }

    const candidates: { path: string; isDirectory: boolean }[] = [];
    if (spec.kind !== "dir") for (const p of filePaths) if (matches(p)) candidates.push({ path: p, isDirectory: false });
    // Directories derived from file paths are never empty, so emptyOnly never matches one.
    if (spec.kind !== "file" && !spec.emptyOnly) for (const d of dirPaths) if (matches(d)) candidates.push({ path: d, isDirectory: true });

    let removed = 0;
    for (const { path, isDirectory } of candidates) {
      if (spec.deletable) {
        const content = isDirectory ? undefined : files[path];
        let ok: boolean;
        try {
          ok = await spec.deletable(
            { size: content === undefined ? 0 : toBytes(content).length, isDirectory, isFile: !isDirectory, mtime: new Date(0) },
            { path, pattern: spec.pattern },
          );
        } catch (cause) {
          throw new FileableError(`deletable() threw for "${path}"`, path, cause);
        }
        if (!ok) continue;
      }
      if (isDirectory) {
        for (const p of Object.keys(files)) if (p.startsWith(`${path}/`)) delete files[p];
      } else {
        delete files[path];
      }
      removed++;
    }
    if (removed === 0 && spec.onMissing !== "ignore") {
      const message = `<Rm target="${spec.pattern}"> matched nothing to remove`;
      if (spec.onMissing === "error") throw new FileableError(message, spec.pattern);
      warnings.push(message);
    }
  }
}

/**
 * Runs the browser-safe pipeline and returns the final files. See the module
 * doc comment for exactly what is and is not supported.
 */
export async function toFiles(tree: unknown, options: ToFilesOptions = {}): Promise<Files> {
  const built = build(cloneDescriptorTree(tree));
  const resolved = await resolve(built, options);
  const laidOut = layout(resolved, options);
  drainBuildContext(); // collection patterns only feed the hash cache; clear the shared buffer

  for (const artifact of laidOut.artifacts) {
    if (artifact.target !== "loose") {
      throw new FileableError(
        `encode="${artifact.target}" (${artifact.containerPath ?? artifact.outputPath}) is not supported in the browser entry point -- ` +
          `use render() from the Node entry point ("@johnhenry/fileable") to produce archives`,
        artifact.outputPath,
      );
    }
  }

  const files: Files = {};
  if (options.existing) {
    for (const [path, content] of Object.entries(options.existing)) setFile(files, path, content);
  }
  const warnings: string[] = [];
  await applyRemovals(laidOut.removals, files, warnings);

  const isExisting = (path: string): boolean => options.existing !== undefined && has(files, path);
  const generated = new Set<string>();
  const pendingLinks: { path: string; target: string; onConflict: ReturnType<typeof parseOnConflict> }[] = [];

  for (const artifact of laidOut.artifacts) {
    if (artifact.kind !== "file") continue;
    const path = artifact.outputPath;
    assertSafePath(path);
    const onConflict = parseOnConflict(artifact.descriptor.props, path);
    if (artifact.content === undefined && artifact.symlinkTo !== undefined) {
      pendingLinks.push({ path, target: artifact.symlinkTo, onConflict });
      continue;
    }
    place(path, artifact.content ?? "", onConflict);
  }

  for (const link of pendingLinks) {
    const parts = link.path.split("/").slice(0, -1);
    for (const seg of link.target.split("/")) {
      if (seg === "..") parts.pop();
      else if (seg !== "." && seg !== "") parts.push(seg);
    }
    const targetPath = parts.join("/");
    if (!has(files, targetPath)) {
      throw new FileableError(
        `symlink ${link.path} -> ${link.target} points at ${JSON.stringify(targetPath)}, which is not a file in the result -- ` +
          "symlinks are materialized as copies in toFiles()",
        link.path,
      );
    }
    place(link.path, files[targetPath], link.onConflict);
  }

  function place(path: string, content: string | Uint8Array, onConflict: ReturnType<typeof parseOnConflict>): void {
    // Only pre-existing content (from `existing`) can conflict; same-build duplicates already threw in Layout.
    if (isExisting(path) && !generated.has(path)) {
      if (onConflict === "error") {
        throw new FileableError(`refusing to overwrite existing file (onConflict="error"): ${path}`, path);
      }
      if (onConflict === "skip") return;
      if (onConflict === "append") content = combine(files[path], content);
      else if (onConflict === "prepend") content = combine(content, files[path]);
    }
    setFile(files, path, content);
    generated.add(path);
  }

  return files;
}
